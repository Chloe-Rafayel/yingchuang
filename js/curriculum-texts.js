    function normalizeQuery(q) {
        return (q || '')
            .replace(/[？?！!。，,\s《》""''「」]/g, '')
            .replace(/(请|给出|提供|翻译|背诵|默写|全文|原文|是什么|内容|怎么写|怎样)/g, '')
            .trim();
    }

    function find(query) {
        if (!query) return null;
        const raw = query.trim();
        const norm = normalizeQuery(raw);
        let best = null;
        let bestLen = 0;

        Object.keys(TEXTS).forEach(function (id) {
            const item = TEXTS[id];
            (item.aliases || []).forEach(function (alias) {
                const a = alias.replace(/[《》]/g, '');
                if (raw.indexOf(alias) >= 0 || raw.indexOf(a) >= 0 ||
                    norm.indexOf(a) >= 0 || a.indexOf(norm) >= 0) {
                    if (a.length > bestLen) {
                        bestLen = a.length;
                        best = item;
                    }
                }
            });
        });
        return best;
    }

